import type {Config} from '~/core/config';
import type {BaseConfig} from '~/core/program';
import type {FileSystem} from './fs';

import {dirname, join, relative} from 'node:path';
import pmap from 'p-map';
import {ok} from 'node:assert';
import {constants as fsConstants} from 'node:fs/promises';

import {bounded, isSubPath, normalizePath, wait} from '~/core/utils';
import {LogLevel, Logger} from '~/core/logger';

import {fs} from './fs';
import {InsecureAccessError} from './errors';
import {SourceService} from './sources';

type GlobOptions = {
    cwd?: AbsolutePath;
    ignore?: string[];
};

export class RunLogger extends Logger {
    proc = this.topic(LogLevel.INFO, 'PROC');
    copy = this.topic(LogLevel.INFO, 'COPY');
}

/**
 * This is transferable context for build command.
 * Use this context to communicate with lower data processing levels.
 */
export class Run<TConfig = BaseConfig> {
    readonly logger: RunLogger;

    readonly config: Config<BaseConfig & TConfig>;

    readonly fs: FileSystem = fs;

    readonly sources = new SourceService();

    readonly normalize: (path: RelativePath) => NormalizedPath = normalizePath;

    readonly input: AbsolutePath;

    readonly originalInput: AbsolutePath;

    protected scopes: Map<string, AbsolutePath> = new Map();

    constructor(config: Config<BaseConfig & TConfig>) {
        this.config = config;
        this.input = config.input;
        this.originalInput = config.input;
        this.logger = new RunLogger(config, [
            (_level, message) => {
                for (const [alias, scope] of this.scopes.entries()) {
                    const clean = message.replace(new RegExp(scope, 'ig'), alias);

                    if (clean === alias) {
                        return message;
                    }

                    message = clean;
                }

                return message;
            },
        ]);
    }

    /**
     * This method is especially written in sync mode to use in run.write method.
     */
    @bounded exists(path: AbsolutePath) {
        try {
            this.statSync(path);
            return true;
        } catch {
            return false;
        }
    }

    /**
     * Run.input bounded read helper
     *
     * Asserts file path is in project scope.
     *
     * @throws {InsecureAccessError}
     * @param {AbsolutePath} path - unixlike absolute path to file
     *
     * @returns {Promise<string>}
     */
    @bounded async read(path: AbsolutePath) {
        await this.assertProjectScope(path);

        return this.fs.readFile(this.sources.resolve(path), 'utf8');
    }

    /** Read selected source metadata, including files not yet staged. */
    @bounded stat(path: AbsolutePath) {
        return this.fs.stat(this.sources.resolve(path));
    }

    /** Read selected source metadata synchronously for Markdown asset decisions. */
    @bounded statSync(path: AbsolutePath) {
        return this.fs.statSync(this.sources.resolve(path));
    }

    /**
     * Declare original inputs consumed through raw Node.js IO or an extension library.
     * A directory declares its eligible subtree; exists/stat alone do not declare descendants.
     * Generated workspace files are regenerated by the extension, not packed as source inputs.
     */
    @bounded depend(path: AbsolutePath) {
        return this.sources.depend(path);
    }

    /** Stage a selected source file for an adapter that requires a physical input. */
    @bounded async materialize(path: AbsolutePath, select = true) {
        await this.assertProjectScope(path);
        return this.sources.materialize(path, select);
    }

    /**
     * Run.input bounded write helper.
     *
     * Asserts file path is in project scope.
     * Drops hardlinks (unlink before write).
     * Creates directory for file.
     * Uses atomic write via temporary file + rename to prevent concurrent writes.
     *
     * @param {AbsolutePath} path - unixlike absolute path to file
     * @param {string} content - file content
     * @param {boolean} force - ignore file exists
     *
     * @returns {Promise<void>}
     */
    @bounded async write(path: AbsolutePath, content: string, force = false) {
        await this.assertProjectScope(path);

        // Move write to next task instead of process it in current microtask.
        // This allow to detect already created files in parallel processing.
        await wait(1);

        // Check if file already exists (fast sync check)
        if (!force && this.exists(path)) {
            return;
        }

        await this.fs.mkdir(dirname(path), {recursive: true});

        // Use atomic write: write to temp file first, then rename
        // rename is atomic on POSIX filesystems, preventing race conditions
        const tempPath = `${path}.tmp.${Date.now()}.${Math.random().toString(36).slice(2)}`;

        try {
            await this.fs.writeFile(tempPath, content, 'utf8');

            // Try atomic rename first (works on POSIX, overwrites existing file atomically)
            try {
                await this.fs.rename(tempPath, path);
            } catch (renameError: unknown) {
                // On Windows, rename may fail if target exists
                // Fall back to unlink + rename
                const error = renameError as Error & {code?: string};
                if (error?.code === 'ENOENT' || error?.code === 'EEXIST') {
                    await this.fs.unlink(path).catch(() => {});
                    await this.fs.rename(tempPath, path);
                } else {
                    throw renameError;
                }
            }
            this.sources.written(path);
        } catch (error) {
            // Clean up temp file on error
            await this.fs.unlink(tempPath).catch(() => {});
            throw error;
        }
    }

    /**
     * Glob wrapper with some default settings
     *
     * @param {string | string[]} pattern
     * @param {GlobOptions} options
     *
     * @returns {NormalizedPath[]}
     */
    @bounded async glob(
        pattern: string | string[],
        options: GlobOptions,
    ): Promise<NormalizedPath[]> {
        const paths = await this.sources.glob(pattern, options);

        return paths.map(normalizePath);
    }

    @bounded async copy(from: AbsolutePath, to: AbsolutePath, ignore: string[] = []) {
        const isFile = (await this.fs.stat(this.sources.resolve(from, false))).isFile();

        if (from === to) {
            return [];
        }

        if (!isFile && isSubPath(from, to)) {
            ignore = [...ignore, `${relative(from, to)}/**`];
        }

        const files: [string, string][] = isFile
            ? [[from, to]]
            : (
                  await (this.sources.active
                      ? this.sources.glob('**', {cwd: from, ignore}, false)
                      : this.glob('**', {cwd: from, ignore}))
              ).map((file) => [join(from, file), join(to, file)]);

        const mkdirPromises = new Map<string, Promise<void>>();

        const ensureDir = (dir: string) => {
            let promise = mkdirPromises.get(dir);
            if (!promise) {
                promise = this.fs.mkdir(dir, {recursive: true}).then(() => {});
                mkdirPromises.set(dir, promise);
            }
            return promise;
        };

        const mode = this.config.copyOnWrite ? fsConstants.COPYFILE_FICLONE : 0;

        await pmap(
            files,
            async ([src, dest]) => {
                const dir = dirname(dest);

                await ensureDir(dir);

                const source = this.sources.resolve(src, !this.sources.isWorkspacePath(dest));
                await this.fs.copyFile(source, dest, mode);
                this.sources.copied(src, dest);
            },
            {concurrency: 30},
        );

        return files;
    }

    /**
     * Remove selected file or directory.
     */
    @bounded async remove(path: AbsolutePath): Promise<void> {
        try {
            await this.fs.rm(path, {recursive: true, force: true});
            this.sources.removed(path);
        } catch {}
    }

    @bounded async realpath(path: AbsolutePath) {
        try {
            return await this.fs.realpath(this.sources.resolve(path));
        } catch {
            return path;
        }
    }

    @bounded realpathSync(path: AbsolutePath) {
        try {
            return this.fs.realpathSync(this.sources.resolve(path)) as AbsolutePath;
        } catch {
            return path;
        }
    }

    private async assertProjectScope(path: AbsolutePath) {
        const scopes = [...this.scopes.values()].map(normalizePath) as AbsolutePath[];
        const source = this.sources.resolve(path, false);
        const lazySource = source !== path && this.sources.isWorkspacePath(path);
        let actual: string;
        if (lazySource) {
            // Original symlinks are dereferenced by native input copying into this logical path.
            actual = path;
        } else if (this.sources.active) {
            actual = await this.fs.realpath(source).catch(() => path);
        } else {
            actual = await this.realpath(path);
        }
        const realpath = normalizePath(actual) as AbsolutePath;
        const isInScope = scopes.some((scope) =>
            this.sources.active
                ? realpath === scope || realpath.startsWith(`${scope.replace(/\/$/, '')}/`)
                : realpath.startsWith(scope),
        );
        ok(isInScope, new InsecureAccessError(path, realpath, scopes));
    }
}
